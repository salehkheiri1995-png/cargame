export const MAX_UPGRADE_LEVEL = 5;

export function getDefaultUpgrades(): VehicleUpgradeLevels {
  return { speed: 0, accel: 0, nitro: 0, handling: 0, braking: 0 };
}

export function getUpgradeCost(car: VehicleConfig, currentLevel: number): number {
  const base = Math.max(120, Math.min(2800, Math.round(car.price * 0.065 + 120)));
  return Math.round((base * Math.pow(1.42, currentLevel)) / 10) * 10;
}

export function computeEffectiveStats(
  car: VehicleConfig,
  upgrades?: VehicleUpgradeLevels
): VehicleStats {
  const u = upgrades ?? getDefaultUpgrades();
  return {
    speed: Math.min(100, car.baseStats.speed + u.speed * 3),
    accel: Math.min(100, car.baseStats.accel + u.accel * 3),
    nitro: Math.min(100, car.baseStats.nitro + u.nitro * 4),
    handling: Math.min(100, car.baseStats.handling + u.handling * 3),
    braking: Math.min(100, car.baseStats.braking + u.braking * 3),
  };
}

export function computePowerIndex(stats: VehicleStats): number {
  return Math.round(
    stats.speed * 2.4 +
      stats.accel * 2.2 +
      stats.nitro * 1.9 +
      stats.handling * 1.8 +
      stats.braking * 1.7
  );
}
